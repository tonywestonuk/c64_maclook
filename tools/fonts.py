def build(name, glyphs, height, spacing, out, dout):
    widths = [0] * 128
    rows = {}
    for ch, art in glyphs.items():
        c = ord(ch)
        w = max(len(r) for r in art)
        assert w <= 8, (name, ch)
        assert len(art) <= height, (name, ch, len(art))
        data = []
        for r in range(height):
            line = art[r] if r < len(art) else ""
            b = 0
            for i, p in enumerate(line):
                if p == '#':
                    b |= 0x80 >> i
            data.append(b)
        rows[c] = data
        widths[c] = w + spacing
        if name == "sysfont" and c == 0x14:
            widths[c] = 10
    out.append(f"{name}_height = {height}")
    out.append(f"{name}_width:")
    for i in range(0, 128, 16):
        out.append("        !byte " + ",".join(str(w) for w in widths[i:i + 16]))
    order = sorted(rows)
    out = dout                  # the rest lives under the I/O chips
    out.append(f"{name}_lo:")
    lo, hi = [], []
    for c in range(128):
        lbl = f"{name}_g{c:02x}" if c in rows else f"{name}_g20"
        lo.append(f"<{lbl}")
        hi.append(f">{lbl}")
    for i in range(0, 128, 8):
        out.append("        !byte " + ",".join(lo[i:i + 8]))
    out.append(f"{name}_hi:")
    for i in range(0, 128, 8):
        out.append("        !byte " + ",".join(hi[i:i + 8]))
    out.append(f"{name}_data:")
    for c in order:
        out.append(f"{name}_g{c:02x}: !byte " + ",".join(f"${b:02x}" for b in rows[c]))
    return rows, widths


def preview(path, fonts):
    """Write a PBM showing every glyph of every font."""
    lines = []
    for rows, widths, height in fonts:
        sample = "".join(chr(c) for c in range(32, 127)) + "\x11\x12\x14"
        canvas = [[0] * 600 for _ in range(height * 2 + 2)]
        x = 0
        y = 0
        for ch in sample:
            c = ord(ch)
            if c not in rows:
                continue
            if x + widths[c] > 600:
                x = 0
                y += height + 1
            for r in range(height):
                for i in range(8):
                    if rows[c][r] & (0x80 >> i):
                        canvas[y + r][x + i] = 1
            x += widths[c]
        lines.extend(canvas)
    with open(path, "w") as f:
        f.write(f"P1\n600 {len(lines)}\n")
        for row in lines:
            f.write("".join("1" if p else "0" for p in row) + "\n")


def main():
    # fonts.asm: heights and widths, in the System's core.  fontdata.asm
    # (next to it): glyph pointers and bitmaps, assembled for the RAM
    # under the I/O chips, where draw_text reads them.
    out = ["; generated by tools/fonts.py - font widths (System core)"]
    dout = ["; generated by tools/fonts.py - glyphs (RAM under I/O, see gfx.asm)"]
    srows, swid = build("sysfont", SYSTEM, 9, 1, out, dout)
    mrows, mwid = build("smallfont", SMALL, 8, 1, out, dout)
    open(sys.argv[1], "w").write("\n".join(out) + "\n")
    open(os.path.join(os.path.dirname(sys.argv[1]), "fontdata.asm"), "w").write("\n".join(dout) + "\n")
    if len(sys.argv) > 2:
        preview(sys.argv[2], [(srows, swid, 9), (mrows, mwid, 8)])


if __name__ == "__main__":
    main()
