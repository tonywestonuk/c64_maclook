#!/usr/bin/env python3
"""Turn ACME's symbol dump of the System into an include file for
applications, so the Finder is linked against the System it runs on."""
import re, sys
out = ["; generated by tools/linksym.py from the System's symbol table"]
for line in open(sys.argv[1]):
    # ACME marks values forced to 16 bit as NAME+2 (e.g. CHRGOT = $0079)
    m = re.match(r'\s*([A-Za-z_][A-Za-z0-9_]*)(\+\d)?\s*=\s*(\$[0-9a-fA-F]+|[0-9]+)', line)
    if m and len(m.group(1)) > 1:      # (one-letter names are !for counters)
        val = m.group(3)
        if m.group(2) == "+2" and val.startswith("$"):
            val = "$%04x" % int(val[1:], 16)
        out.append(f"{m.group(1)} = {val}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
