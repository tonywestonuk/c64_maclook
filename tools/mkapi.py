#!/usr/bin/env python3
"""Publish the System's API.

Reads src/jumptab.asm, src/public.asm, src/zp.asm and the System's
symbol table, and writes:

  build/sysapi.asm  what applications include: jump table entries,
                    public data, public zero page registers, constants
  docs/api.md       the same, as documentation

usage: mkapi.py build/system.sym build/sysapi.asm docs/api.md
"""
import re
import sys

sym_file, out_asm, out_md = sys.argv[1:4]

# --- the System's symbols -------------------------------------------
syms = {}
for line in open(sym_file):
    # ACME marks values forced to 16 bit as NAME+2 (e.g. CHRGOT = $0079)
    m = re.match(r'\s*([A-Za-z_][A-Za-z0-9_]*)(\+\d)?\s*=\s*(\$[0-9a-fA-F]+|[0-9]+)', line)
    if m:
        v = m.group(3)
        syms[m.group(1)] = int(v[1:], 16) if v.startswith('$') else int(v)

def addr(n):
    return syms[n]

# --- jump table -----------------------------------------------------
jt_base = addr('JUMP_TABLE')
entries = []        # (section, name, address, description)
section = ''
for line in open('src/jumptab.asm'):
    m = re.match(r';\s*---\s*(.*)', line)
    if m:
        section = m.group(1).strip()
        continue
    m = re.match(r'\s+jmp\s+(\w+)\s*(?:;\s*(.*))?$', line)
    if m:
        entries.append((section, m.group(1), jt_base + 3 * len(entries),
                        (m.group(2) or '').strip()))

# --- public data ----------------------------------------------------
public = []         # (section, name, address, comment)
public_eq = []      # equates defined in public.asm
section = 'general'
def public_lines(path):
    for line in open(path):
        m = re.match(r'!source\s+"([^"]+)"', line)
        if m:
            yield from public_lines(m.group(1))
        else:
            yield line
for line in public_lines('src/public.asm'):
    m = re.match(r';\s*---\s*(.*?)\s*-*$', line)
    if m:
        section = m.group(1).strip()
        continue
    m = re.match(r'(\w+):\s*(?:!\w+[^;]*)?(?:;\s*(.*))?$', line)
    if m:
        public.append((section, m.group(1), addr(m.group(1)), (m.group(2) or '').strip()))
        continue
    m = re.match(r'(\w+)\s*=', line)
    if m:
        public_eq.append(m.group(1))

# --- zero page ------------------------------------------------------
zp = []             # (name, address, comment)
state = None
for line in open('src/zp.asm'):
    if '@public' in line:
        state = 'public'
    elif '@private' in line:
        state = 'private'
    m = re.match(r'(\w+)\s*=\s*\$([0-9a-fA-F]+)\s*(?:;\s*(.*))?$', line)
    if m and state == 'public':
        zp.append((m.group(1), int(m.group(2), 16), (m.group(3) or '').strip()))

# --- constants ------------------------------------------------------
PREFIXES = ('WF_', 'P_', 'M_', 'CL_', 'ICON_', 'B_', 'MF_', 'EDIT_', 'MOD_',
            'DLG_', 'CUR_', 'K_', 'FS_', 'FSW_')
NAMES = ['MAXWIN', 'NUM_MENUS', 'TITLE_H', 'SB_W', 'W_H', 'ACT_NONE', 'SYS_ACT',
         'APP_BASE', 'PAGE_BASE', 'DESK_Y1', 'SPRPTR', 'NUM_PATTERNS', 'JUMP_TABLE']
# the BASIC ROM's floating point entry points (fp.asm)
for line in open('src/fp.asm'):
    m = re.match(r'([A-Z][A-Z0-9_]*)\s*=\s*\$', line)
    if m:
        NAMES.append(m.group(1))
taken = {n for _, n, _, _ in entries} | {n for _, n, _, _ in public} | {n for n, _, _ in zp}
consts = {}
for n, v in syms.items():
    if n in taken:
        continue
    if n.startswith(PREFIXES) and n.upper() == n or n in NAMES or n in public_eq:
        consts[n] = v
missing = [n for n in NAMES if n not in syms]
if missing:
    sys.exit(f"mkapi: not in the symbol table: {missing}")

# --- build/sysapi.asm -----------------------------------------------
out = ["; generated by tools/mkapi.py - the System's API, for applications",
       "; (do not edit: see src/jumptab.asm, src/public.asm, src/zp.asm)", "",
       "; jump table"]
for _, n, a, d in entries:
    out.append(f"{n} = ${a:04x}")
out += ["", "; public data"]
for _, n, a, _ in public:
    out.append(f"{n} = ${a:04x}")
out += ["", "; zero page registers"]
for n, a, _ in zp:
    out.append(f"{n} = ${a:02x}")
out += ["", "; constants"]
for n in sorted(consts):
    v = consts[n]
    out.append(f"{n} = ${v:04x}" if v > 255 else f"{n} = {v}")
open(out_asm, "w").write("\n".join(out) + "\n")

# --- docs/api.md ----------------------------------------------------
md = ["# The System's API", "",
      "Generated by `tools/mkapi.py` from `src/jumptab.asm`, `src/public.asm` and",
      "`src/zp.asm`. Applications include `build/sysapi.asm`, which has the same",
      "names and addresses, and use nothing else of the System.", "",
      "## Calling the System", "",
      f"Every call goes through the jump table at `${jt_base:04x}`: `jsr fill_rect`",
      "assembles to `jsr` into the table, which jumps on to the routine. The",
      "table's order never changes and new calls are added at the end, so an",
      "application keeps working when the System is rebuilt. Parameters go in",
      "A, X, Y and the zero page registers below.", "",
      "## Jump table", ""]
sec = None
for s, n, a, d in entries:
    if s != sec:
        md += ["", f"### {s[0].upper() + s[1:]}", "", "| Address | Call | |", "|---|---|---|"]
        sec = s
    md.append(f"| `${a:04x}` | `{n}` | {d} |")
md += ["", "## Public data", "",
       "Fixed addresses after the jump table. Applications read these and set the",
       "ones that are parameters (`dlg_*`, `zr_*`, settings).", ""]
sec = None
for s, n, a, c in public:
    if s != sec:
        md += ["", f"### {s[0].upper() + s[1:]}", "", "| Address | Name | |", "|---|---|---|"]
        sec = s
    md.append(f"| `${a:04x}` | `{n}` | {c} |")
md += ["", "## Zero page registers", "",
       "`t0`-`t7` are scratch for anyone. `q0`-`q3`, `u0`-`u7` and `jvec` belong to",
       "the application between calls; the System's high level calls (windows,",
       "menus, dialogs) may use them too.", "",
       "| Address | Name | |", "|---|---|---|"]
for n, a, c in zp:
    md.append(f"| `${a:02x}` | `{n}` | {c} |")
md += ["", "Constants (`WF_`, `P_`, `M_`, `CL_`, `ICON_`, `MF_`, key codes and so on) are",
       "in `build/sysapi.asm`.", ""]
open(out_md, "w").write("\n".join(md))
print(f"API: {len(entries)} calls, {len(public)} public data, {len(zp)} registers, {len(consts)} constants")
