#!/usr/bin/env python3
"""The System's overlays (src/ovl_*.asm, see src/overlay.asm).

  mkovl.py stubs build/ovl_stubs.asm
      Before the core is assembled: the overlay tables and one stub per
      overlay entry ("name: jsr ovl_call / !byte overlay, entry"), from
      the "; @overlay" header and the "; @entries" table of each overlay.

  mkovl.py syms build/system.sym
      After the core is assembled: build/ovl<n>_sys.asm for each overlay,
      every symbol of the core except the names the overlay defines
      itself (so inside an overlay its own routines are called directly,
      and everything else goes to the core, or to another overlay's stub).
"""
import glob
import os
import re
import sys


def overlays():
    found = []
    for path in sorted(glob.glob("src/ovl_*.asm")):
        text = open(path).read()
        m = re.search(r';\s*@overlay\s+(\d+)\s+"([^"]+)"\s+\$([0-9a-fA-F]+)', text)
        if not m:
            sys.exit(f"mkovl: {path} has no '; @overlay n \"file\" $addr' line")
        body = text[text.index("@entries"):text.index("; @end")]
        entries = re.findall(r'^\s+jmp\s+(\w+)', body, re.M)
        found.append({"id": int(m.group(1)), "file": m.group(2),
                      "base": int(m.group(3), 16), "src": path, "entries": entries})
    found.sort(key=lambda o: o["id"])
    ids = [o["id"] for o in found]
    if ids != list(range(1, len(found) + 1)):
        sys.exit(f"mkovl: overlay numbers must be 1..n, found {ids}")
    for o in found:
        if o["base"] not in (0x4000, 0x5000):
            sys.exit(f"mkovl: {o['src']}: an overlay starts at $4000 or $5000")
    return found


def defined_names(path, seen=None):
    """Labels and equates defined by a source file and what it includes."""
    seen = seen if seen is not None else set()
    if path in seen or not os.path.exists(path):
        return set()
    seen.add(path)
    names = set()
    for line in open(path):
        m = re.match(r'!source\s+"([^"]+)"', line)
        if m:
            if "_sys.asm" not in m.group(1):
                names |= defined_names(m.group(1), seen)
            continue
        m = re.match(r'([A-Za-z_]\w*)\s*(:|=|\s+!)', line)
        if m:
            names.add(m.group(1))
    return names


def stubs(out):
    ovl = overlays()
    lines = ["; generated by tools/mkovl.py - the System's overlays (src/ovl_*.asm)",
             f"OVL_COUNT = {len(ovl)}",
             "ovl_page:    !byte " + ", ".join(f"${o['base'] >> 8:02x}" for o in ovl),
             "ovl_region:  !byte " + ", ".join(str((o['base'] - 0x4000) >> 12) for o in ovl),
             "ovl_path_lo: !byte " + ", ".join(f"<ovl_path{o['id']}" for o in ovl),
             "ovl_path_hi: !byte " + ", ".join(f">ovl_path{o['id']}" for o in ovl)]
    for o in ovl:
        lines.append(f'ovl_path{o["id"]}: !text "{o["file"]}", 0')
    for o in ovl:
        lines.append(f"; {o['file']}")
        for i, name in enumerate(o["entries"]):
            lines.append(f"{name}: jsr ovl_call")
            lines.append(f"        !byte {o['id']}, {i}")
    open(out, "w").write("\n".join(lines) + "\n")


def syms(symfile):
    core = []
    for line in open(symfile):
        # ACME marks values forced to 16 bit as NAME+2 (e.g. CHRGOT = $0079)
        m = re.match(r'\s*([A-Za-z_][A-Za-z0-9_]*)(\+\d)?\s*=\s*(\$[0-9a-fA-F]+|[0-9]+)', line)
        if m and len(m.group(1)) > 1:      # (one-letter names are !for counters)
            val = m.group(3)
            if m.group(2) == "+2" and val.startswith("$"):
                val = "$%04x" % int(val[1:], 16)
            core.append((m.group(1), val))
    for o in overlays():
        own = defined_names(o["src"])
        lines = [f"; generated by tools/mkovl.py - the System core's symbols for {o['file']}"]
        lines += [f"{n} = {v}" for n, v in core if n not in own]
        open(f"build/ovl{o['id']}_sys.asm", "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if sys.argv[1] == "stubs":
        stubs(sys.argv[2])
    else:
        syms(sys.argv[2])
