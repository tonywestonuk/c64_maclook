def parse(art):
    rows = [r for r in art.split("\n") if r != ""]
    w = max(len(r) for r in rows)
    return [r.ljust(w) for r in rows], w


def mask_of(rows, w):
    h = len(rows)
    outside = [[False] * (w + 2) for _ in range(h + 2)]
    grid = [[' '] * (w + 2) for _ in range(h + 2)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            grid[y + 1][x + 1] = c
    stack = [(0, 0)]
    outside[0][0] = True
    while stack:
        x, y = stack.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < w + 2 and 0 <= ny < h + 2 and not outside[ny][nx] and grid[ny][nx] != '#':
                outside[ny][nx] = True
                stack.append((nx, ny))
    return [[not outside[y + 1][x + 1] for x in range(w)] for y in range(h)]


def outline_of(mask, w):
    h = len(mask)
    out = [[False] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if not mask[y][x]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if not (0 <= nx < w and 0 <= ny < h) or not mask[ny][nx]:
                    out[y][x] = True
    return out


def to_bytes(bits, wb):
    out = []
    for row in bits:
        for b in range(wb):
            v = 0
            for i in range(8):
                x = b * 8 + i
                if x < len(row) and row[x]:
                    v |= 0x80 >> i
            out.append(v)
    return out


def hexrow(data):
    return ",".join(f"${b:02x}" for b in data)


# Desk accessory icons: not on the disk until desk accessories come back
# as files.
UNUSED_ICONS = {'calc', 'notepad', 'puzzle', 'clock', 'cpanel', 'readme',
                # applications' own icons: for when the Finder reads them from
                # the application files
                'finder', 'clipboard', 'scrapbook', 'paint', 'brickles', 'sheet'}

SYSTEM_ICONS = {'caution', 'stop', 'note', 'arrowup', 'arrowdn', 'arrowlt', 'arrowrt', 'grow', 'radio', 'radioon',
                'c64logo', 'happymac'}
# System icons used only by the Interface overlay (alerts, start-up)
OVERLAY_ICONS = {'caution', 'stop', 'note', 'happymac'}
PLAIN_ICONS = {'arrowup', 'arrowdn', 'arrowlt', 'arrowrt', 'grow', 'c64logo'}


def main():
    sys_out, fin_out, spr_out = sys.argv[1], sys.argv[2], sys.argv[3]
    out_sys = ["; generated by tools/icons.py - System icons"]
    out_fin = ["; generated by tools/icons.py - Finder icons"]
    out_ovl = ["; generated by tools/icons.py - icons of the Interface overlay"]
    preview = []
    for name, art in ICONS.items():
        if name in UNUSED_ICONS:
            continue
        rows, w = parse(art)
        h = len(rows)
        wb = (w + 7) // 8
        img = [[c == '#' for c in r] for r in rows]
        mask = mask_of(rows, w)
        outline = outline_of(mask, w)
        out = out_ovl if name in OVERLAY_ICONS else out_sys if name in SYSTEM_ICONS else out_fin
        out.append(f"icon_{name}: !byte {wb},{h},{w}")
        out.append("        !byte " + hexrow(to_bytes(img, wb)))
        if name not in PLAIN_ICONS:
            out.append("        !byte " + hexrow(to_bytes(mask, wb)))
        if name not in SYSTEM_ICONS:
            out.append("        !byte " + hexrow(to_bytes(outline, wb)))
        preview.append((img, mask, outline, w, h))

    # (SMALL: small icons for View by Small Icon, not used yet)

    # the desktop patterns are public data: patterns.asm, next to the
    # System's icons, is included in src/public.asm
    out_pat = ["; generated by tools/icons.py - desktop patterns", "patterns:"]
    for p in PATTERNS:
        out_pat.append("        !byte " + hexrow(p))
    out_pat.append(f"NUM_PATTERNS = {len(PATTERNS)}")
    open(os.path.join(os.path.dirname(sys_out), "patterns.asm"), "w").write("\n".join(out_pat) + "\n")

    # cursors -> sprite pairs at $C400 (black, white, black, white, ...)
    spr = []
    out_sys.append("; cursor hotspots (sprite pixel of the hot spot)")
    for i, (name, ((hx, hy), art)) in enumerate(CURSORS.items()):
        rows, w = parse(art)
        shape = [[False] * 24 for _ in range(21)]
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == '#':
                    shape[y + 1][x + 1] = True
        grown = [[False] * 24 for _ in range(21)]
        for y in range(21):
            for x in range(24):
                if shape[y][x]:
                    for dy in (-1, 0, 1):
                        for dx in (-1, 0, 1):
                            if 0 <= y + dy < 21 and 0 <= x + dx < 24:
                                grown[y + dy][x + dx] = True
        spr.append(to_bytes(shape, 3) + [0])
        spr.append(to_bytes(grown, 3) + [0])
        out_sys.append(f"CUR_{name.upper()} = {i}")
        out_sys.append(f"cur_hx_{name} = {hx + 1}")
        out_sys.append(f"cur_hy_{name} = {hy + 1}")
    out_sys.append("cursor_hx: !byte " + ",".join(f"cur_hx_{n}" for n in CURSORS))
    out_sys.append("cursor_hy: !byte " + ",".join(f"cur_hy_{n}" for n in CURSORS))
    open(sys_out, "w").write("\n".join(out_sys) + "\n")
    open(fin_out, "w").write("\n".join(out_fin) + "\n")
    open(os.path.join(os.path.dirname(sys_out), "icons_ovl.asm"), "w").write("\n".join(out_ovl) + "\n")

    with open(spr_out, "w") as f:
        f.write("; generated by tools/icons.py - cursor sprites, copied to $c400\n")
        for sp in spr:
            for i in range(0, 64, 16):
                f.write("        !byte " + hexrow(sp[i:i + 16]) + "\n")

    if len(sys.argv) > 4:
        W = 3 * 26
        H = sum(p[4] + 2 for p in preview)
        canvas = [[0] * W for _ in range(H)]
        y0 = 0
        for img, mask, outline, w, h in preview:
            for k, bits in enumerate((img, mask, outline)):
                for y in range(h):
                    for x in range(w):
                        if bits[y][x]:
                            canvas[y0 + y][k * 26 + x] = 1
            y0 += h + 2
        with open(sys.argv[4], "w") as f:
            f.write(f"P1\n{W} {H}\n")
            for row in canvas:
                f.write("".join("1" if p else "0" for p in row) + "\n")


if __name__ == "__main__":
    main()
