"""Icons, mouse cursors and desktop patterns, drawn as ASCII art.

Icons: '#' black, '.' white (inside the icon if enclosed), ' ' outside.
The mask is everything that is not reachable from outside the picture,
and the drag outline is the edge of the mask.  Output per icon:

  icon_<name>: !byte width_bytes, height, width_pixels
               image rows, mask rows, outline rows   (row-major)

System icons are never dragged, so they leave out the outline, and the
ones only drawn with ICON_PLAIN leave out the mask too.

Cursors become pairs of hires sprites: black shape on top, white
outline (shape grown by one pixel) underneath.
"""
